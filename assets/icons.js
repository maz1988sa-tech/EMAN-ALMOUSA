export function icon(name, size = 20, extraClass = '') {
  const d = ICON_PATHS[name];
  if (!d) return '';
  return `<svg class="ic ${extraClass}" viewBox="0 0 24 24" width="${size}" height="${size}"`
    + ' fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round"'
    + ` stroke-linejoin="round" aria-hidden="true" focusable="false">${d}</svg>`;
}

// Drop an icon into a slot marked with data-icon, so markup stays declarative.
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    if (el.dataset.iconDone) return;
    el.innerHTML = icon(el.dataset.icon, Number(el.dataset.iconSize) || 20);
    el.dataset.iconDone = '1';
  });
}

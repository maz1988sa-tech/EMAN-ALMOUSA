-- حدودُ ما هو خارج مدينة الرياض — لأنّ الحكم يقع على حيٍّ له حدّ.
--
-- بيانات الأحياء (٧د) تغطّي مدينة الرياض وحدها. وستٌّ من المواضع التي
-- سمّتها صاحبة العمل خارجها إداريًّا: الخرج والمزاحمية والدرعية
-- والعمارية والغروب والموسى. وكانت كلُّها تسقط في سطر «خارج الأحياء
-- المعروفة» — وهو سطرٌ واحد بحكمٍ واحد، وهي تحتاج ثلاثة أحكام مختلفة:
-- رفض · شخصان فأكثر · تسعيرة خاصّة. فلا مفرّ من إعطاء كلٍّ حدَّه.
--
-- والمصدر OpenStreetMap عبر Nominatim، مضلّعاتٌ إدارية حقيقية:
--
--   https://nominatim.openstreetmap.org/search
--     ?q=Al+Kharj&format=json&polygon_geojson=1&limit=1&countrycodes=sa
--   ...وكذلك Al+Muzahimiyah، وAd+Diriyah مع
--     &viewbox=46.0,25.3,47.4,24.2&bounded=1
--     (بدونها يُطابق «الدرعية» بلدةً في القصيم — وقع فعلًا)
--
-- وإحداثيّات GeoJSON بترتيب [طول، عرض]، وجدولُنا [عرض، طول] — فتُقلب.
--
-- والغروب والموسى لا حدَّ لهما مستقلًّا، وهما داخل محافظة الدرعية
-- وحكمُهما حكمُها، فيغطّيهما حدُّها.
--
-- **والعمارية لا مضلّع منشور لها — نقطة فقط.** فحدُّها هنا مستطيلٌ
-- تقريبيّ حول البلدة (±٠٫٠٢٥ عرضًا و±٠٫٠٢٨ طولًا ≈ ٥٫٥ كم ضلعًا)،
-- وهذا مُثبت في `en` لئلّا يُظنّ رسميًّا. وينطبق صحيحًا لأنّ الأصغر
-- يفوز عند التداخل، فيسبق حكمُه حكمَ الدرعية المحيط به.
